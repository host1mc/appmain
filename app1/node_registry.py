def placement_capacity_available() -> bool:
    def _probe(conn):
        cur = conn.cursor()
        cur.execute(_COUNT_NODES)
        if _fetch_count(cur) < 1:
            return True
        cur.execute(_SELECT_NODE_WITH_FREE_CAPACITY)
        return cur.fetchone() is not None

    try:
        return _with_conn(_probe)
    except Exception as exc:
        message = str(exc)
        if _MISSING_TABLE not in message and _MISSING_COLUMN not in message:
            raise
        return True


def pick_node_for_new_server(conn=None):
    def _query(placement_conn):
        cur = placement_conn.cursor()
        cur.execute(_SELECT_NODE_WITH_FREE_CAPACITY)
        row = cur.fetchone()
        if row is not None:
            return int(row[0])
        cur.execute(_COUNT_NODES)
        if _fetch_count(cur) > 0:
            raise NodeCapacityError(
                "every configured node is full or disabled, so there is no room "
                "for a new server right now; raise a node's capacity or add "
                "another node"
            )
        return None

    try:
        if conn is None:
            return _run_with_heal(_query)
        return _run_on_conn_with_heal(conn, _query)
    except NodeCapacityError:
        raise
    except Exception as exc:
        message = str(exc)
        if _MISSING_TABLE not in message and _MISSING_COLUMN not in message:
            raise
        return None
