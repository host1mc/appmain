    if key is None:
        return False

    def _do_delete(conn):
        cur = conn.cursor()
        if _servers_on_node(cur, key) > 0:
            raise ValueError(
                "this node still hosts servers, and existing servers are never "
                "migrated; set its capacity to 0 to stop new placements instead "
                "of deleting it"
            )
        cur.execute(_DELETE_NODE, {"nid": key})
        conn.commit()
        return (cur.rowcount or 0) == 1

    return _run_with_heal(_do_delete)


